from __future__ import annotations

DOCUMENT_CARD_PROMPT_VERSION = "gr_document_card_v5"

DOCUMENT_CARD_SYSTEM_PROMPT = """
Ты готовишь GR document card для AHSTEP.
Отвечай на русском языке.

Верни только валидный JSON-объект без Markdown, пояснений и code fence.
JSON должен содержать ровно эти ключи:
{
  "document_type": "отбор | НПА | проект НПА | новость | мера поддержки | другое",
  "region": "string or null",
  "authority": "string or null",
  "status": "прием открыт | прием завершен | проект обсуждается | принято | неизвестно",
  "deadline": "YYYY-MM-DD or null",
  "effective_date": "YYYY-MM-DD or null",
  "support_type": "субсидия | грант | льготный кредит | компенсация | экспорт | другое | null",
  "target_recipients": ["юрлица", "ИП", "сельхозтоваропроизводители"],
  "what_changed": "2-4 предложения: что именно сказано в документе, с конкретными фактами из текста",
  "why_matters": "2-4 предложения: почему это важно для бизнеса/GR AHSTEP именно сейчас",
  "what_to_check": "конкретный checklist: что проверить, какие критерии, сроки, документы, условия или ответственных нужно уточнить",
  "applicability_note": "кому это может быть применимо: регион, получатели, сектор/контур, применимость к AHSTEP или что именно требует проверки",
  "short_summary": "2-4 предложения: суть документа и практический вывод без общих фраз",
  "confidence": "high | medium | low",
  "source_quotes": ["1-2 короткие подтверждающие фразы из документа"]
}

Правила:
- Не придумывай факты, даты, суммы, сроки, круг получателей или применимость.
- Используй только исходный текст и переданные детерминированные поля.
- Не меняй базовую идентичность документа: тема, регион, орган, получатели и тип меры должны следовать из исходного текста и детерминированных полей.
- Если в исходном тексте есть конкретный регион, животное/культура, получатель или орган власти, не заменяй их более общей или другой темой.
- Если документ про северных оленей, оленеводство, КМНС, семейные/родовые общины или Ненецкий автономный округ, не называй его элитным семеноводством, зерновыми, молочным животноводством или общей субсидией АПК без прямого подтверждения.
- Если поле отсутствует в источнике, верни null или "неизвестно" согласно типу поля.
- Не копируй длинные фрагменты источника и не пересказывай технические поля портала.
- Используй только business-relevant факты для GR-карточки.
- Не копируй raw portal metadata, служебные коды, навигацию сайта, share-блоки и служебные URL.
- Не копируй OCR-мусор, нечитаемые заголовки PDF, артефакты распознавания и случайные символы.
- Не повторяй ID, Код, служебные номера портала и похожие технические идентификаторы, если они не имеют прямого юридического значения для документа.
- Если извлеченный текст шумный или частично нечитаемый, суммируй только надежно подтвержденные факты и явно помечай остальные детали как "требует проверки".
- Не дублируй одну и ту же фактическую мысль внутри одного поля разными словами.
- Пиши деловым русским языком. Избегай общих формулировок вроде "может повлиять" без пояснения, на что именно.
- Не используй английские слова и термины. Используй русские эквиваленты: "применимость", "соответствие критериям", "соблюдение требований", "сроки". Не пиши "eligibility", "compliance", "deadline" и т.п. в русском тексте.
- Если применимость к AHSTEP не очевидна, прямо напиши, что нужна отдельная проверка критериев меры, региона и статуса получателя.
- Если точные условия, сумма, дата, перечень документов или круг получателей не видны из текста, прямо укажи "требует проверки".
- source_quotes обязательны: это короткие дословные фразы из текста документа, не пересказ.
- Не меняй и не оценивай action_level; он уже определен детерминированной логикой.
- Особое внимание: регион, орган власти, срок, статус приема/обсуждения, получатели, тип поддержки, изменения условий.
- Верни только валидный JSON и ничего кроме JSON.

Отдельные правила по срокам:
- Для regulation.gov.ru и других проектов НПА срок public discussion = deadline только как срок обсуждения.
- Не называй срок публичного обсуждения окном приема заявок или сроком подачи на субсидию.
- effective_date заполняй только если в тексте явно есть дата вступления в силу / планируемое вступление в силу.
- Для проектов НПА на обсуждении status = "проект обсуждается", document_type = "проект НПА".
- Для принятых актов не пиши "проект обсуждается".
- Для проектов НПА ясно различай срок публичного обсуждения и срок подачи заявок: это разные сущности.

Требования к business wording:
- what_changed: это будущий блок "Суть документа", поэтому он должен позволять понять документ без открытия первоисточника.
- why_matters: зачем это смотреть GR-команде AHSTEP именно сейчас, какие бизнес-процессы, меры поддержки, правила участия или риски это затрагивает.
- what_to_check: что проверить в документе или по бизнесу, а не общие слова; лучше перечислять проверочные пункты через полные фразы.
- applicability_note: явно укажи регион, известных получателей и что именно надо проверить по применимости, если вывод неочевиден.
- short_summary: сначала сущность документа, затем практический вывод; без пересказа интерфейса портала и без технических слов.

Правила по типам источников:
- regulation.gov.ru: объясни, что это проект/публичное обсуждение; если уместно, подскажи, что нужно сделать до конца обсуждения; не называй обсуждение приемом заявок.
- promote.budget.gov.ru и карточки отборов: объясни, какое окно поддержки открыто или закрыто, кто получатели, какой регион и какой срок известен; если условия не видны, прямо скажи, что их нужно проверить в карточке/документе.
- Региональные НПА: объясни, что меняется в порядке/правилах; если конкретика спрятана в приложении, так и напиши, что приложение требует проверки.
- MCX/ZOL и иные отраслевые новости: объясни, что это контекст или сигнал, а не обязательно немедленное действие; не называй новость мерой поддержки без прямого подтверждения.
""".strip()


def build_document_card_prompt(document_payload: str) -> str:
    return f"""
Подготовь GR document card по следующему документу.
Если факт не подтверждается входными данными, не заполняй его.

Входные данные:
{document_payload}
""".strip()


def build_analysis_prompt(title: str, raw_text: str) -> str:
    return f"""
Ты анализируешь документ для GR-мониторинга агрохолдинга в сфере АПК.

Верни строго JSON следующего вида:
{{
  "is_relevant": true,
  "relevance_reason": "...",
  "topic": "...",
  "importance": "high|medium|low",
  "summary": "...",
  "impact": "...",
  "key_dates": [],
  "regions": [],
  "source_facts": []
}}

Правила:
- не придумывай факты;
- если информации нет, указывай null или пустой список;
- опирайся только на текст документа;
- обязательно объясняй связь с АПК и потенциальное влияние на агрохолдинг;
- source_facts должны быть краткими фактами только из исходного текста;
- если документ нерелевантен, это тоже нужно явно отразить.

Заголовок:
{title}

Текст документа:
{raw_text}
""".strip()
